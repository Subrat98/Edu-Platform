export const getCbcsSummaryData = (): CbcsSummaryData => {
  const total = initialCbcsProgrammes.length; // 14
  const withCbcs = initialCbcsProgrammes.filter(
    (p) => p.cbcsType === "Choice Based Credit System (CBCS)" || p.cbcsType === "Elective Course System"
  ).length; // 14
  const adoptionPct = Number(((withCbcs / (total || 1)) * 100).toFixed(1));
  const totalStudents = initialElectiveCourseOptions.reduce((acc, c) => acc + c.enrolledStudentsCount, 0);

  return {
    totalProgrammesOffered: total,
    programmesWithCbcs: withCbcs,
    adoptionPercentage: adoptionPct,
    benchmarkPercentage: 100.0,
    totalElectiveCoursesOffered: initialElectiveCourseOptions.length,
    totalStudentsEnrolledInElectives: totalStudents,
    programmeRecords: initialCbcsProgrammes,
    notifications: initialUniversityNotifications,
    electiveCourses: initialElectiveCourseOptions,
  };
};
