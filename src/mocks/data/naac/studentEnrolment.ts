export const getStudentEnrolmentData = (): StudentProfileEnrolmentData => {
  const totalSanctionedFiveYears = initialEnrolmentYearRecords.reduce(
    (acc, y) => acc + y.sanctionedSeats,
    0
  ); // 3300
  const totalAdmittedFiveYears = initialEnrolmentYearRecords.reduce(
    (acc, y) => acc + y.admittedStudents,
    0
  ); // 3122
  const fiveYearEnrolmentPercentage = Number(
    ((totalAdmittedFiveYears / (totalSanctionedFiveYears || 1)) * 100).toFixed(1)
  ); // 94.6%

  return {
    fiveYearEnrolmentPercentage,
    benchmarkPercentage: 90.0,
    totalSanctionedFiveYears,
    totalAdmittedFiveYears,
    yearlyRecords: initialEnrolmentYearRecords,
    programmeRecords: initialProgrammeEnrolmentRecords,
    reservationPolicy: {
      scPercent: 16.25,
      stPercent: 22.50,
      obcPercent: 11.25,
      openPercent: 50.00,
      pwdPercent: 5.00,
    },
  };
};
